import pytest
from unittest.mock import patch
from src.external_api import get_transaction_amount


@patch('requests.get')
def test_get_transaction_amount(mock_get, test_transaction_list):
    mock_get.return_value.json.return_value = {'result': 10000.00}
    assert get_transaction_amount(test_transaction_list[0]) == 10000.00
    mock_get.assert_called_once()


def test_get_transaction_amount_correct_rub(test_transaction_list):
    print(test_transaction_list[3])
    assert get_transaction_amount(test_transaction_list[3]) == 43318.34


